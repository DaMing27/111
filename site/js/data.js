/* ---------- 工具：按 ID 查条目 ---------- */
window.getEntry = function (id) {
  return window.ENTRIES.find(function (e) { return e.id === id; });
};

window.getEntriesByMap = function (mapKey) {
  return window.ENTRIES.filter(function (e) { return e.map === mapKey; });
};

window.getCategoryLabel = function (mapKey, categoryId) {
  var m = window.MAPS[mapKey];
  if (!m) return categoryId;
  var c = m.categories.find(function (c) { return c.id === categoryId; });
  return c ? c.name : categoryId;
};
